export async function ensureDefaultAccounts(tx: Tx, schoolId: string) {
  for (const a of DEFAULT_ACCOUNTS) {
    await tx.ledgerAccount.upsert({
      where: { schoolId_code: { schoolId, code: a.code } },
      create: { schoolId, ...a },
      update: {},
    });
  }
}

type SystemLine = { accountCode: string; debitPaise?: number; creditPaise?: number };

/**
 * Posts a balanced entry generated by the system (invoice issue, payment, reversal).
 * Called only from services that have already authorized the business action.
 */
export async function postSystemEntry(
  tx: Tx,
  args: { schoolId: string; schoolCode: string; date: Date; narration: string; source: JournalSource; sourceId: string; createdById: string; lines: SystemLine[]; reversesId?: string },
) {
  const accounts = await tx.ledgerAccount.findMany({
    where: { schoolId: args.schoolId, code: { in: args.lines.map((l) => l.accountCode) } },
  });
  const byCode = new Map(accounts.map((a) => [a.code, a.id]));
  const lines = args.lines.map((l) => {
    const accountId = byCode.get(l.accountCode);
    if (!accountId) throw new Error(`Ledger account ${l.accountCode} missing for school.`);
    return { accountId, debitPaise: l.debitPaise ?? 0, creditPaise: l.creditPaise ?? 0 };
  });
  const problem = validateJournalLines(lines);
  if (problem) throw new Error(`Unbalanced system entry: ${problem}`);
  const n = await nextDocumentNumber(tx, args.schoolId, "journal");
  return tx.journalEntry.create({
    data: {
      schoolId: args.schoolId,
      number: formatDocNumber("JV", args.schoolCode, n),
      date: args.date,
      narration: args.narration,
      source: args.source,
      sourceId: args.sourceId,
      reversesId: args.reversesId,
      createdById: args.createdById,
      lines: { create: lines },
    },
  });
}

export const manualEntryInput = z.object({
  schoolId: z.string().min(1),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Enter a valid date"),
  narration: z.string().trim().min(3, "Narration is required").max(300),
  lines: z
    .array(z.object({ accountId: z.string().min(1), debitPaise: z.number().int().min(0), creditPaise: z.number().int().min(0) }))
    .min(2, "A journal entry needs at least two lines"),
});

/** Manual journal entry: only explicitly authorized finance personnel and designated owners. */
export async function createManualEntry(actor: Actor, raw: z.input<typeof manualEntryInput>) {
  const input = parseInput(manualEntryInput, raw);
  assertCan(actor, "finance.ledger.create", { schoolId: input.schoolId }, "Only authorized finance staff can create ledger entries.");
  const problem = validateJournalLines(input.lines);
  if (problem) throw invalid(problem);
  const school = await prisma.school.findUniqueOrThrow({ where: { id: input.schoolId } });
  const accounts = await prisma.ledgerAccount.count({ where: { schoolId: school.id, id: { in: input.lines.map((l) => l.accountId) } } });
  if (accounts !== new Set(input.lines.map((l) => l.accountId)).size) throw invalid("One or more accounts do not belong to this school.");

  return prisma.$transaction(async (tx) => {
    const n = await nextDocumentNumber(tx, school.id, "journal");
    const entry = await tx.journalEntry.create({
      data: {
        schoolId: school.id,
        number: formatDocNumber("JV", school.code, n),
        date: toDbDate(input.date),
        narration: input.narration,
        source: "MANUAL",
        createdById: actor.userId,
        lines: { create: input.lines },
      },
    });
    const total = input.lines.reduce((s, l) => s + l.debitPaise, 0);
    await audit(
      {
        actorUserId: actor.userId, organizationId: school.organizationId, schoolId: school.id,
        action: "ledger.entry.create", entityType: "JournalEntry", entityId: entry.id,
        summary: `Manual journal ${entry.number} for ${total} paise: ${input.narration}`,
      },
      tx,
    );
    return entry;
  });
}

/** Posted entries are never edited or deleted: a mirror-image reversal entry is created instead. */
export async function reverseManualEntry(actor: Actor, entryId: string, reason: string) {
  const entry = await prisma.journalEntry.findUnique({ where: { id: entryId }, include: { lines: true, school: true, reversal: true } });
  if (!entry) throw notFound("Journal entry");
  assertCan(actor, "finance.ledger.update", { schoolId: entry.schoolId }, "Only authorized finance staff can reverse ledger entries.");
  if (entry.source !== "MANUAL") throw invalid("System entries are reversed through their source document (for example, reversing the payment).");
  if (entry.reversal || entry.reversesId) throw conflict("This entry has already been reversed or is itself a reversal.");
  if (reason.trim().length < 5) throw invalid("Give a reason for the reversal.");

  return prisma.$transaction(async (tx) => {
    const n = await nextDocumentNumber(tx, entry.schoolId, "journal");
    const rev = await tx.journalEntry.create({
      data: {
        schoolId: entry.schoolId,
        number: formatDocNumber("JV", entry.school.code, n),
        date: entry.date,
        narration: `Reversal of ${entry.number}: ${reason.trim()}`,
        source: "MANUAL",
        reversesId: entry.id,
        createdById: actor.userId,
        lines: { create: entry.lines.map((l) => ({ accountId: l.accountId, debitPaise: l.creditPaise, creditPaise: l.debitPaise })) },
      },
    });
    await audit(
      {
        actorUserId: actor.userId, organizationId: entry.school.organizationId, schoolId: entry.schoolId,
        action: "ledger.entry.reverse", entityType: "JournalEntry", entityId: entry.id,
        summary: `Reversed ${entry.number} with ${rev.number}`,
      },
      tx,
    );
    return rev;
  });
}

export async function listLedger(actor: Actor, schoolId: string) {
  assertCan(actor, "finance.ledger.read", { schoolId });
  const [accounts, balances, entries] = await Promise.all([
    prisma.ledgerAccount.findMany({ where: { schoolId }, orderBy: { code: "asc" } }),
    prisma.journalLine.groupBy({
      by: ["accountId"],
      where: { entry: { schoolId } },
      _sum: { debitPaise: true, creditPaise: true },
    }),
    prisma.journalEntry.findMany({
      where: { schoolId },
      include: { lines: { include: { account: true } }, reversal: { select: { number: true } } },
      orderBy: [{ date: "desc" }, { number: "desc" }],
      take: 50,
    }),
  ]);
  const sums = new Map(balances.map((b) => [b.accountId, b._sum]));
  return {
    accounts: accounts.map((a) => {
      const s = sums.get(a.id);
      const dr = s?.debitPaise ?? 0;
      const cr = s?.creditPaise ?? 0;
      // Natural balance sign: assets/expenses are debit-normal, the rest credit-normal.
      const balance = a.type === "ASSET" || a.type === "EXPENSE" ? dr - cr : cr - dr;
      return { ...a, debitPaise: dr, creditPaise: cr, balancePaise: balance };
    }),
    entries,
  };
}
